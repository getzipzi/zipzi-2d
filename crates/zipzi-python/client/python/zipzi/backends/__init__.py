"""Local and Connected transports execute the same v4 contract."""
from collections.abc import Mapping
from typing import Any, Protocol

class Backend(Protocol):
    @property
    def connection_info(self) -> Mapping[str, Any] | None: ...
    def request(self, operation: dict[str, Any]) -> Any: ...
    def binary_request(self, operation: dict[str, Any], payload: bytes = b'') -> tuple[Any, bytes]: ...
    def recover(self) -> Any: ...
    def close(self) -> None: ...
