"""Render offline Markdown from generated values and public Python declarations.

Parse source instead of importing the SDK: replay must describe the newly
rendered contract, even when the installed client is older or absent.
"""

import ast
from copy import deepcopy
import json
import keyword
from pathlib import Path
import re

PREFIX = "client/python/zipzi/"
DIRECTORY = PREFIX + "docs/reference/"
HEADER = "<!-- @generated by zipzi-python/tools/generate.py; DO NOT EDIT. -->\n"
SOURCES = (
    "__init__.py",
    "_kernel.py",
    "_errors.py",
    "_documentation.py",
    "results.py",
    "_value_codec.py",
)


def exports(tree):
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets
        ):
            return ast.literal_eval(node.value)
    return []


def name(node):
    return node.name.id if isinstance(node, ast.TypeAlias) else node.name


def declarations(tree):
    return {
        name(n): n
        for n in tree.body
        if isinstance(n, (ast.ClassDef, ast.FunctionDef, ast.TypeAlias))
    }


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", "<br>")


def signature(node):
    node = deepcopy(node)
    node.body = [ast.Expr(value=ast.Constant(value=Ellipsis))]
    return ast.unparse(node)


def render(generated, definitions, package, sources=None):
    if sources is None:
        sources = {
            p: (Path(package) / PREFIX / p).read_text(encoding="utf-8") for p in SOURCES
        }
    trees = {p: ast.parse(source) for p, source in sources.items()}
    root_exports = exports(trees["__init__.py"])
    pages = {}
    locations = {}
    shapes = dict(definitions)
    for type_name, shape in definitions.items():
        for variant in shape.get("variants", []):
            shapes[type_name + variant["rust_name"]] = variant

    def add_page(filename, title, entries, intro=""):
        pages[filename] = (title, entries, intro)
        for path, node in entries:
            locations[path] = filename + "#" + path.lower().replace(".", "-")

    for filename, title, inputs in (
        (
            "runtime.md",
            "Runtime and offline help",
            ("__init__.py", "_kernel.py", "_documentation.py"),
        ),
        ("errors.md", "Failures and recovery", ("_errors.py",)),
    ):
        entries = [
            ("zipzi." + n, node)
            for p in inputs
            for n, node in declarations(trees[p]).items()
            if n in root_exports
        ]
        add_page(
            filename,
            title,
            entries,
            "Signatures use `v` for `zipzi.values`, `r` for `zipzi.results`, and `WireMap` for `Mapping[str, Any]`. Obtain runtime objects through `local()`, `connect()` and their public methods.",
        )
    result_names = exports(trees["results.py"])
    add_page(
        "results.md",
        "Response shapes",
        [
            ("zipzi.results." + n, node)
            for n, node in declarations(trees["results.py"]).items()
            if n in result_names
        ],
        ast.get_docstring(trees["results.py"]) or "",
    )
    value = declarations(trees["_value_codec.py"])["Value"]
    add_page(
        "value-codec.md",
        "Shared value methods",
        [("Value", value)],
        "Generated record and union instances inherit these methods. String enums use Python's `StrEnum` interface.",
    )
    for path, source in sorted(generated.items()):
        if path.startswith(PREFIX + "values/") and not path.endswith("__init__.py"):
            domain = Path(path).stem
            tree = ast.parse(source)
            add_page(
                "values-" + domain + ".md",
                "Values: " + domain,
                [
                    ("zipzi.values." + n, node)
                    for n, node in declarations(tree).items()
                    if n in exports(tree)
                ],
                f"Import from `zipzi.values.{domain}` or `zipzi.values`; both expose the same classes. Record and variant constructors are frozen and keyword-only. Required fields must be supplied. Defaults below use wire JSON; the constructor decodes them into the annotated Python type.\n\n[Shared value methods](value-codec.md)",
            )

    def related(node, path):
        references = set()
        # Restrict cross-links to annotations, bases and type aliases, not bodies.
        snippets = []
        for child in ast.walk(node):
            if isinstance(child, ast.arg) and child.annotation:
                snippets.append(child.annotation)
            elif isinstance(child, ast.AnnAssign):
                snippets.append(child.annotation)
            elif isinstance(child, ast.FunctionDef) and child.returns:
                snippets.append(child.returns)
        if isinstance(node, ast.ClassDef):
            snippets.extend(node.bases)
        if isinstance(node, ast.TypeAlias):
            snippets.append(node.value)
        for snippet in snippets:
            for token in re.findall(
                r"[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*", ast.unparse(snippet)
            ):
                if token.startswith("r."):
                    candidate = "zipzi.results." + token[2:]
                elif token.startswith("v.") or "." in token:
                    candidate = "zipzi.values." + token.split(".")[-1]
                else:
                    prefix = (
                        "zipzi.results."
                        if path.startswith("zipzi.results.")
                        else "zipzi.values."
                        if path.startswith("zipzi.values.")
                        else "zipzi."
                    )
                    candidate = prefix + token
                if candidate in locations and candidate != path:
                    references.add(candidate)
        return ", ".join(f"[{p}]({locations[p]})" for p in sorted(references))

    def entry(path, node, level=2, overloads=()):
        anchor = path.lower().replace(".", "-")
        lines = [f'<a id="{anchor}"></a>', "", "#" * level + " " + path, ""]
        if isinstance(node, ast.TypeAlias):
            return lines + [
                "```python",
                ast.unparse(node),
                "```",
                "",
                "Related: " + related(node, path),
                "",
            ]
        if isinstance(node, ast.FunctionDef):
            lines += [
                "```python",
                *[signature(n) for n in overloads],
                signature(node),
                "```",
                "",
            ]
        else:
            params = (
                "[" + ", ".join(ast.unparse(p) for p in node.type_params) + "]"
                if node.type_params
                else ""
            )
            lines += [
                "```python",
                "class "
                + node.name
                + params
                + (
                    "(" + ", ".join(ast.unparse(b) for b in node.bases) + ")"
                    if node.bases
                    else ""
                ),
                "```",
                "",
            ]
        documentation = ast.get_docstring(node)
        if documentation and path.startswith("zipzi.values."):
            # Field prose belongs beside its type/default, not in a duplicate block.
            documentation = documentation.split("\n\nFields:", 1)[0]
        if documentation:
            lines += [documentation.rstrip(), ""]
        if isinstance(node, ast.ClassDef):
            fields = [
                n
                for n in node.body
                if isinstance(n, ast.AnnAssign)
                and isinstance(n.target, ast.Name)
                and not n.target.id.startswith("_")
            ]
            shape = (
                shapes.get(node.name, {}) if path.startswith("zipzi.values.") else {}
            )
            defaults = {
                f["name"] + ("_" if keyword.iskeyword(f["name"]) else ""): f
                for f in shape.get("fields", [])
            }
            if fields:
                generated_value = path.startswith("zipzi.values.")
                lines += [
                    "| Field | Type |"
                    + (
                        " Constructor default (wire JSON) | Description |"
                        if generated_value
                        else ""
                    ),
                    "| --- | --- |" + (" --- | --- |" if generated_value else ""),
                ]
                for field in fields:
                    default = "Required"
                    metadata = defaults.get(field.target.id, {})
                    if metadata.get("default") is not None:
                        raw = metadata["default"]
                        if raw == {"kind": "null"}:
                            raw = None
                        elif raw == {"kind": "empty_string"}:
                            raw = ""
                        default = (
                            "`"
                            + cell(json.dumps(raw, ensure_ascii=False, sort_keys=True))
                            + "`"
                        )
                    elif (
                        isinstance(field.value, ast.Constant)
                        and field.value.value is None
                    ):
                        default = "`null` (`None`)"
                    lines.append(
                        f"| `{field.target.id}` | `{cell(ast.unparse(field.annotation))}` |"
                        + (
                            f" {default} | {cell(metadata.get('doc') or '')} |"
                            if generated_value
                            else ""
                        )
                    )
                lines.append("")
            if any(ast.unparse(b) == "StrEnum" for b in node.bases):
                docs = {
                    v.get("name", v.get("wire_name")): v.get("doc", "")
                    for v in shape.get("variants", [])
                }
                lines += ["| Member | Value | Description |", "| --- | --- | --- |"]
                for member in node.body:
                    if isinstance(member, ast.Assign):
                        val = ast.literal_eval(member.value)
                        lines.append(
                            f"| `{ast.unparse(member.targets[0])}` | `{cell(repr(val))}` | {cell(docs.get(val) or '')} |"
                        )
                lines.append("")
            variants = [
                n
                for p, n in pages[locations[path].split("#")[0]][1]
                if isinstance(n, ast.ClassDef)
                and any(ast.unparse(b) == node.name for b in n.bases)
            ]
            if variants and path.startswith("zipzi.values."):
                lines += [
                    "Variants: "
                    + ", ".join(
                        f"[{n.name}]({locations['zipzi.values.' + n.name]})"
                        for n in variants
                    ),
                    "",
                ]
            overloads_by_name = {}
            for method in node.body:
                if isinstance(method, ast.FunctionDef) and not method.name.startswith(
                    "_"
                ):
                    is_overload = any(
                        ast.unparse(d) == "overload" for d in method.decorator_list
                    )
                    if is_overload:
                        overloads_by_name.setdefault(method.name, []).append(method)
                    else:
                        lines += entry(
                            path + "." + method.name,
                            method,
                            level + 1,
                            overloads_by_name.get(method.name, ()),
                        )
        links = related(node, path)
        if links:
            lines += ["Related: " + links, ""]
        return lines

    output = {}
    for filename, (title, entries, intro) in pages.items():
        lines = [
            HEADER,
            "# " + title,
            "",
            "[API index](index.md) · [Usage guide](../guide.md)",
            "",
            intro,
            "",
        ]
        lines += [f"- [{path}]({locations[path]})" for path, _ in entries] + [""]
        for path, node in entries:
            lines += entry(path, node)
        output[DIRECTORY + filename] = "\n".join(lines)
    index = [
        HEADER,
        "# Python API reference",
        "",
        "Generated from the Rust authoring contract and public Python declarations. Edit those sources, then run `uv run --locked python crates/zipzi-python/tools/generate.py`; `--check` detects drift. No host, native adapter or network is needed to read this reference.",
        "",
        "[Getting started](../getting-started.md) · [Lifetimes](../lifecycle.md) · [Usage guide](../guide.md) · [Executable recipes](../recipes.py)",
        "",
        "Read installed files with `importlib.resources.files('zipzi').joinpath('docs/reference/index.md').read_text(encoding='utf-8')`. For focused interactive help, use `zipzi.describe('Session.query').format()`.",
        "",
        "## Pages",
        "",
    ]
    index += [f"- [{title}]({filename})" for filename, (title, _, _) in pages.items()]
    index += ["", "## Public entrypoints", ""]
    for exported in root_exports:
        if exported == "values":
            index.append(
                "- `zipzi.values`: domain pages above; each type is also available from its domain module."
            )
        elif exported == "results":
            index.append("- [zipzi.results](results.md)")
        else:
            path = "zipzi." + exported
            destination = locations.get(path) or locations.get(
                "zipzi.values." + exported
            )
            if destination:
                index.append(f"- [{path}]({destination})")
    output[DIRECTORY + "index.md"] = "\n".join(index) + "\n"
    return output
