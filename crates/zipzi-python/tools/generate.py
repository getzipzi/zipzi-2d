#!/usr/bin/env python3
"""Generate v4 typed values from the compiled Contract, with deterministic replay."""

import argparse
import ast
import json
import keyword
import re
import sys
from pathlib import Path
import subprocess

PACKAGE = Path(__file__).resolve().parents[1]
ROOT = PACKAGE.parents[1]
sys.path.insert(0, str(PACKAGE / "tools"))
from codegen import outputs, reference
from codegen.value_modules import module_for

TARGETS = frozenset(
    {
        "client/python/zipzi/values.py",
        "client/python/zipzi/values/__init__.py",
        "client/python/zipzi/_schema.json",
        "schema/authoring.json",
    }
)
HEADER = "# @generated by zipzi-python/tools/generate.py; DO NOT EDIT.\n"


def render(contract):
    if contract.get("protocol") != "zipzi-runtime-v4":
        raise ValueError("Unsupported authoring contract")
    definitions = {}
    raw_definitions = {}

    def normalize(s):
        if isinstance(s, list):
            return [normalize(v) for v in s]
        if not isinstance(s, dict):
            return s
        if s.get("kind") in ("record", "serde_record", "union", "serde_enum"):
            raw = s["name"]
            if "<" in raw:
                base, args = raw.split("<", 1)
                name = base.split("::")[-1] + "".join(
                    x.strip(" >").split("::")[-1] for x in args.split(",")
                )
            else:
                name = raw.split("::")[-1]
            if not name.isidentifier() or keyword.iskeyword(name):
                raise ValueError("Invalid public type name " + name)
            if name in raw_definitions and raw_definitions[name] != s:
                raise ValueError("Conflicting public type " + name)
            raw_definitions[name] = s
            if name not in definitions:
                definitions[name] = None
                definitions[name] = {k: normalize(v) for k, v in s.items()}
            return {"kind": "ref", "name": name}
        return {k: normalize(v) for k, v in s.items()}

    roots = normalize(contract)

    owners = {name: module_for(name) for name in definitions}

    def annotation(s, module):
        k = s["kind"]
        if k == "ref":
            if s["name"] not in definitions:
                raise ValueError("Unresolved public type " + s["name"])
            owner = owners[s["name"]]
            return (owner + "." if owner != module else "") + s["name"]
        if k == "string":
            return "str"
        if k == "bool":
            return "bool"
        if k in ("f32", "f64"):
            return "float"
        if k in ("u8", "u16", "u32", "u64", "usize", "i32", "i64"):
            return "int"
        if k == "json":
            return "object"
        if k == "shared":
            return annotation(s["item"], module)
        if k == "optional":
            return annotation(s["item"], module) + " | None"
        if k in ("sequence", "array"):
            return "tuple[" + annotation(s["item"], module) + ", ...]"
        if k == "tuple":
            return "tuple[" + ", ".join(annotation(x, module) for x in s["items"]) + "]"
        if k in ("string_map", "index_map"):
            return (
                "Mapping["
                + ("str" if k == "string_map" else annotation(s["key"], module))
                + ", "
                + annotation(s["value"], module)
                + "]"
            )
        raise ValueError("Unsupported public shape " + str(s))

    def fields(shape, type_name, module):
        lines = []
        for f in shape.get("fields", []):
            if f.get("skip"):
                continue
            name = f["name"] + ("_" if keyword.iskeyword(f["name"]) else "")
            field_type = annotation(f["shape"], module)
            if "default" in f and f["default"] is not None:
                suffix = (
                    " = field(default_factory=lambda: _default("
                    + type_name
                    + ", "
                    + repr(name)
                    + "))"
                )
            elif f["shape"]["kind"] == "optional":
                suffix = " = None"
            else:
                suffix = ""
            lines.append("    " + name + ": " + field_type + suffix)
        return lines

    def documentation(shape, fallback):
        lines = [shape.get("doc") or fallback]
        documented = [
            f for f in shape.get("fields", []) if f.get("doc") and not f.get("skip")
        ]
        if documented:
            lines += ["", "Fields:"]
            lines += [f"{f['name']}: {f['doc']}" for f in documented]
        # Real multiline docstrings remain readable in both source and help().
        body = "\n".join(lines).replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
        return (
            ['    """' + body.split("\n")[0]]
            + ["    " + line if line else "" for line in body.split("\n")[1:]]
            + ['    """']
        )

    modules = {}
    exports = {}
    public = []
    for name, s in sorted(definitions.items()):
        module = owners[name]
        out = []
        names = [name]
        public.append(name)
        if s["kind"] in ("serde_enum", "union"):
            variants = s["variants"]
            if all(not v["fields"] for v in variants):
                out += ["class " + name + "(StrEnum):"] + documentation(
                    s, name + " choices."
                )
                for v in variants:
                    member = re.sub(r"(?<!^)(?=[A-Z])", "_", v["rust_name"]).upper()
                    out += [
                        "    "
                        + member
                        + " = "
                        + repr(v.get("name", v.get("wire_name")))
                    ]
            else:
                out += (
                    ["class " + name + "(Value):"]
                    + documentation(
                        s, name + " variants; inspect subclasses for constructors."
                    )
                    + ["    _type = " + repr(name)]
                )
                for v in variants:
                    variant_name = name + v["rust_name"]
                    public.append(variant_name)
                    names.append(variant_name)
                    out += (
                        [
                            "",
                            "@dataclass(frozen=True, kw_only=True, repr=False)",
                            "class " + variant_name + "(" + name + "):",
                        ]
                        + documentation(v, v["rust_name"] + " variant of " + name + ".")
                        + ["    _variant = " + repr(v.get("name", v.get("wire_name")))]
                        + fields(v, variant_name, module)
                    )
        else:
            out += (
                [
                    "@dataclass(frozen=True, kw_only=True, repr=False)",
                    "class " + name + "(Value):",
                ]
                + documentation(s, name + " contract value.")
                + ["    _type = " + repr(name)]
                + fields(s, name, module)
            )
        out += [""]
        modules.setdefault(module, []).extend(out)
        exports.setdefault(module, []).extend(names)

    def all_names(names):
        lines = ["__all__ = ["]
        for index in range(0, len(names), 4):
            lines.append(
                "    "
                + ", ".join(repr(name) for name in names[index : index + 4])
                + ","
            )
        return lines + ["]", ""]

    output = {}
    for module, declarations in sorted(modules.items()):
        used = {
            node.id
            for node in ast.walk(ast.parse("\n".join(declarations)))
            if isinstance(node, ast.Name)
        }
        dependencies = used & modules.keys()
        header = [
            HEADER,
            f'"""Generated {module.replace("_", " ")} values; available through zipzi.values too."""',
            "from __future__ import annotations",
        ]
        if "Mapping" in used:
            header.append("from collections.abc import Mapping")
        dataclass_imports = [name for name in ("dataclass", "field") if name in used]
        if dataclass_imports:
            header.append("from dataclasses import " + ", ".join(dataclass_imports))
        if "StrEnum" in used:
            header.append("from enum import StrEnum")
        codec_imports = [
            original
            for name, original in (
                ("Value", "Value"),
                ("_default", "default as _default"),
            )
            if name in used
        ]
        if codec_imports:
            header.append("from .._value_codec import " + ", ".join(codec_imports))
        # Import modules rather than their classes: annotations can cross domain
        # cycles without reading a partially initialized class at import time.
        header += [
            f"from . import {dependency} as {dependency}"
            for dependency in sorted(dependencies)
        ]
        output[f"client/python/zipzi/values/{module}.py"] = "\n".join(
            header + [""] + declarations + all_names(exports[module])
        )

    index = [
        HEADER,
        '"""Generated domain values with a shared import entrypoint.\n\n'
        "Use zipzi.values.Mesh or zipzi.values.meshes.Mesh; they are the same type.\n"
        'Browse domains with zipzi.describe("values").\n"""',
        "from .._value_codec import register as _register",
        "",
    ]
    for module, names in sorted(exports.items()):
        index += [f"from . import {module} as {module}", f"from .{module} import ("]
        index += [f"    {name} as {name}," for name in names]
        index += [")", ""]
    index += [
        "CONTRACT = " + repr(contract["protocol"]),
        "",
        "_register(globals())",
        "",
    ]
    output["client/python/zipzi/values/__init__.py"] = "\n".join(
        index + all_names(sorted(modules) + public)
    )
    output.update(
        {
            "client/python/zipzi/_schema.json": json.dumps(
                {"_generated_by": outputs.OWNER, "definitions": definitions},
                indent=2,
                sort_keys=True,
                ensure_ascii=False,
            )
            + "\n",
            "schema/authoring.json": json.dumps(
                {
                    "_generated_by": outputs.OWNER,
                    "roots": roots,
                    "definitions": definitions,
                },
                indent=2,
                sort_keys=True,
                ensure_ascii=False,
            )
            + "\n",
        }
    )
    output.update(reference.render(output, definitions, PACKAGE))
    return output


def write_outputs(output, check=False, package=PACKAGE):
    return outputs.write_outputs(output, check, package, TARGETS)


def read_export(text):
    def unique_object(pairs):
        obj = {}
        for key, value in pairs:
            if key in obj:
                raise ValueError(f"Duplicate schema key {key!r}")
            obj[key] = value
        return obj

    return json.loads(text, object_pairs_hook=unique_object)


def export_contract():
    result = subprocess.run(
        [
            "cargo",
            "run",
            "--locked",
            "--quiet",
            "-p",
            "zipzi-contract",
            "--bin",
            "authoring-schema",
        ],
        cwd=ROOT,
        text=True,
        capture_output=True,
    )
    if result.returncode:
        sys.stderr.write(result.stderr)
        result.check_returncode()
    return read_export(result.stdout)


def generate(check=False, contract=None, package=PACKAGE):
    output = render(export_contract() if contract is None else contract)
    changed = write_outputs(output, check, package)
    if check and changed:
        raise SystemExit("Generated v4 drift: " + ", ".join(changed))
    print("v4 authoring values and API reference: " + ("verified" if check else "generated"))
    return output


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    p.add_argument("--schema", type=Path, help="Replay a compiled schema")
    args = p.parse_args()
    generate(
        args.check,
        read_export(args.schema.read_text(encoding="utf-8")) if args.schema else None,
    )
