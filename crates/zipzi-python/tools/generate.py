#!/usr/bin/env python3
"""Generate v4 typed values from the compiled Contract, with deterministic replay."""
import argparse
import json
import keyword
import sys
from pathlib import Path
import subprocess

PACKAGE = Path(__file__).resolve().parents[1]
ROOT = PACKAGE.parents[1]
sys.path.insert(0, str(PACKAGE / 'tools'))
from codegen import outputs
TARGETS = frozenset({'client/python/zipzi/values.py', 'schema/authoring.json'})
HEADER = '# @generated by zipzi-python/tools/generate.py; DO NOT EDIT.\n'


def render(contract):
    if contract.get('protocol') != 'zipzi-runtime-v4':
        raise ValueError('Unsupported authoring contract')
    definitions = {}
    raw_definitions = {}
    def normalize(s):
        if isinstance(s, list): return [normalize(v) for v in s]
        if not isinstance(s, dict): return s
        if s.get('kind') in ('record', 'serde_record', 'union', 'serde_enum'):
            raw = s['name']
            if '<' in raw:
                base, args = raw.split('<',1)
                name = base.split('::')[-1] + ''.join(x.strip(' >').split('::')[-1] for x in args.split(','))
            else:
                name = raw.split('::')[-1]
            if not name.isidentifier() or keyword.iskeyword(name):
                raise ValueError('Invalid public type name '+name)
            if name in raw_definitions and raw_definitions[name] != s:
                raise ValueError('Conflicting public type '+name)
            raw_definitions[name] = s
            if name not in definitions:
                definitions[name] = None
                definitions[name] = {k: normalize(v) for k, v in s.items()}
            return {'kind': 'ref', 'name': name}
        return {k: normalize(v) for k, v in s.items()}
    roots = normalize(contract)
    def annotation(s):
        k = s['kind']
        if k == 'ref':
            if s['name'] not in definitions:
                raise ValueError('Unresolved public type '+s['name'])
            return s['name']
        if k == 'string': return 'str'
        if k == 'bool': return 'bool'
        if k in ('f32', 'f64'): return 'float'
        if k in ('u8','u16','u32','u64','usize','i32','i64'): return 'int'
        if k == 'json': return 'object'
        if k == 'shared': return annotation(s['item'])
        if k == 'optional': return annotation(s['item'])+' | None'
        if k in ('sequence', 'array'): return 'tuple['+annotation(s['item'])+', ...]'
        if k == 'tuple': return 'tuple['+', '.join(annotation(x) for x in s['items'])+']'
        if k in ('string_map','index_map'): return 'Mapping['+('str' if k == 'string_map' else annotation(s['key']))+', '+annotation(s['value'])+']'
        raise ValueError('Unsupported public shape '+str(s))
    def fields(shape):
        lines = []
        for f in shape.get('fields', []):
            if f.get('skip'): continue
            name = f['name'] + ('_' if keyword.iskeyword(f['name']) else '')
            field_type = annotation(f['shape'])
            if 'default' in f and f['default'] is not None:
                default = f['default']
                if default == {'kind': 'null'}: default = None
                if default == {'kind': 'empty_string'}: default = ''
                suffix = ' = field(default_factory=lambda: _decode('+repr(f['shape'])+', '+repr(default)+'))'
            elif f['shape']['kind'] == 'optional': suffix = ' = None'
            else: suffix = ''
            lines.append('    '+name+': '+field_type+suffix)
        return lines
    out = [HEADER, 'from __future__ import annotations', 'from collections.abc import Mapping',
        'from dataclasses import dataclass, field', 'from enum import StrEnum',
        'from ._value_codec import Value, decode as _decode, register as _register', '',
        'CONTRACT = '+repr(contract['protocol']), '']
    public = []
    for name, s in sorted(definitions.items()):
        public.append(name)
        if s['kind'] in ('serde_enum','union'):
            variants = s['variants']
            if all(not v['fields'] for v in variants):
                out += ['class '+name+'(StrEnum):', '    '+repr(s.get('doc',''))]
                for v in variants:
                    import re
                    member = re.sub(r'(?<!^)(?=[A-Z])', '_', v['rust_name']).upper()
                    out += ['    '+member+' = '+repr(v.get('name',v.get('wire_name')))]
            else:
                out += ['class '+name+'(Value):', '    '+repr(s.get('doc','')), '    _type = '+repr(name)]
                for v in variants:
                    variant_name = name+v['rust_name']
                    public.append(variant_name)
                    out += ['', '@dataclass(frozen=True, kw_only=True)', 'class '+variant_name+'('+name+'):',
                        '    '+repr(v.get('doc','')), '    _variant = '+repr(v.get('name',v.get('wire_name')))] + fields(v)
        else:
            out += ['@dataclass(frozen=True, kw_only=True)', 'class '+name+'(Value):', '    '+repr(s.get('doc','')), '    _type = '+repr(name)] + fields(s)
        out += ['']
    out += ['_register('+repr(definitions)+', globals())', '__all__ = '+repr(public), '']
    return {'client/python/zipzi/values.py': '\n'.join(out),
        'schema/authoring.json': json.dumps({'_generated_by':outputs.OWNER,'roots':roots,'definitions':definitions}, indent=2, sort_keys=True, ensure_ascii=False)+'\n'}


def write_outputs(output, check=False, package=PACKAGE):
    return outputs.write_outputs(output, check, package, TARGETS)


def read_export(text):
    def unique_object(pairs):
        obj = {}
        for key, value in pairs:
            if key in obj:
                raise ValueError(f'Duplicate schema key {key!r}')
            obj[key] = value
        return obj

    return json.loads(text, object_pairs_hook=unique_object)


def export_contract():
    result = subprocess.run(['cargo','run','--locked','--quiet','-p','zipzi-contract','--bin','authoring-schema'], cwd=ROOT, text=True, capture_output=True)
    if result.returncode:
        sys.stderr.write(result.stderr)
        result.check_returncode()
    return read_export(result.stdout)


def generate(check=False, contract=None, package=PACKAGE):
    output = render(export_contract() if contract is None else contract)
    changed = write_outputs(output, check, package)
    if check and changed: raise SystemExit('Generated v4 drift: '+', '.join(changed))
    print('v4 authoring values: '+('verified' if check else 'generated'))
    return output


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check',action='store_true')
    p.add_argument('--schema',type=Path,help='Replay a compiled schema')
    args=p.parse_args()
    generate(args.check, read_export(args.schema.read_text(encoding='utf-8')) if args.schema else None)
