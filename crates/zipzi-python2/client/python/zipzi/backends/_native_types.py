from .._generated import values as modeling
from .._generated.resource_backends import NativeResources
from typing import Callable, Literal, Protocol
from .. import _operations as ops, sampling, scene
from .._generated.protocols import NativeQueries
from ..events import Cursor
from .._values import Source

class NativeRuntime(NativeQueries, NativeResources, Protocol):
    def estimate_observation(self, session: object, edit: object | None, poses: sampling.Inputs, view: modeling.ObservationView) -> object: ...
    def estimate_preview_observation(self, preview: object, times: tuple[float,...], view: modeling.ObservationView, geometry: bool, queries: tuple[modeling.SpatialQuery,...]) -> object: ...
    def observation_job(self, session: object, edit: object | None, poses: sampling.Inputs, view: modeling.ObservationView, expected: Source | None) -> object: ...
    def spatial_job(self, session: object, edit: object | None, poses: sampling.Inputs, queries: tuple[modeling.SpatialQuery,...], expected: Source | None) -> object: ...
    def create_preview(self, session: object, edit: object | None, expected: Source | None) -> object: ...
    def preview_state(self, preview: object) -> object: ...
    def apply_preview(self, preview: object, command: modeling.PreviewCommand) -> object: ...
    def sample_preview(self, preview: object, times: tuple[float,...], geometry: bool, incremental: bool, queries: tuple[modeling.SpatialQuery,...], view: modeling.ObservationView | None) -> object: ...
    def runtime_capabilities(self) -> object: ...
    def runtime_limits(self) -> object: ...
    def detach_session(self, session: object) -> object: ...
    def close_session(self, session: object, discard_modified: bool) -> object: ...
    def collection_page(self, session: object, edit: object | None, collection: str, name: str | None, limit: int, cursor: str | None) -> object: ...
    def read_selection(self, session: object, edit: object | None, collection: str, ids: tuple[str,...], expected: Source | None) -> object: ...
    def prepare_image_job(self, path: str | None, blob: object | None) -> object: ...
    def capture_image(self, session: object, edit: object | None, id: str) -> object: ...
    def editor_context(self,session:object)->object: ...
    def project(self, session: object | None, request: modeling.ProjectRequest) -> object: ...
    def buffer_create(self, length: int) -> object: ...
    def buffer_append(self, blob: object, offset: int, data: bytes) -> object: ...
    def buffer_seal(self, blob: object) -> object: ...
    def buffer_read(self, blob: object, offset: int, length: int) -> object: ...
    def prepare_image_buffer(self, width: int, height: int, blob: object) -> object: ...
    def object_ref(self, session: object, kind: str, id: str) -> object: ...
    def resolve_ref(self, reference: object) -> object: ...
    def ref_capabilities(self, reference: object) -> object: ...
    def label_address(self, reference: object) -> object: ...
    def label_plan(self, address: object, name: str) -> object: ...
    def capture_address(self, session: object, selector: modeling.AddressSelector) -> object: ...
    def address_plan(self, address: object, patch: modeling.AddressPatch) -> object: ...
    def modeling_capabilities(self, reference: object, domain: modeling.CapabilityDomain) -> object: ...
    def collection_capabilities(self, session: object, query: modeling.CollectionQuery) -> object: ...
    def sample_job(self, session: object, edit: object | None, poses: sampling.Inputs, checks: sampling.Checks, expected: Source | None) -> object: ...
    def modeling_plan_job(self, session: object, edit: object | None, intent: modeling.ModelingCommand) -> object: ...
    def modeling_records(self, session: object, edit: object | None, query: modeling.ModelingQuery) -> object: ...
    def deletion_page(self, plan: object, section: modeling.DeletionSection, offset: int, limit: int) -> object: ...
    def modeling_plan(self, session: object, edit: object | None, intent: modeling.ModelingCommand) -> object: ...
    def scene(self, session: object, edit: object | None, ids: tuple[str, ...]) -> object: ...
    def scene_plan(self, session: object, edit: object | None, operation: scene.Operation) -> object: ...
    def bindings(self, session: object, edit: object | None, ids: tuple[str, ...] | None) -> object: ...
    def sample(self, session: object, edit: object | None, poses: sampling.Inputs, checks: sampling.Checks, expected: Source | None) -> object: ...
    def subscribe(self, session: object) -> object: ...
    def events(self, cursor: Cursor, limit: int) -> object: ...
    def parameters(self, session: object, edit: object | None, ids: tuple[str, ...] | None) -> object: ...
    def meshes(self, session: object, edit: object | None, ids: tuple[str, ...]) -> object: ...
    contract: str
    def close(self) -> object: ...
    def create_session(self, document_id: str | None) -> object: ...
    def info(self, session: object) -> object: ...
    def list_sessions(self) -> object: ...
    def attach(self, runtime: str, serial: int) -> object: ...
    def begin_edit(self, session: object, label: str) -> object: ...
    def apply(self, edit: object, operations: tuple[ops.WireOperation, ...]) -> object: ...
    def prepare_image(self, width: int, height: int, rgba: bytes) -> object: ...
    def release_handle(self, kind: Literal["image", "plan", "reference", "address", "buffer", "preview"], token: object) -> object: ...
    def statistics(self) -> object: ...
    def release_edit(self, edit: object) -> object: ...
    def commit(self, edit: object) -> object: ...
    def save(self, session: object, path: str) -> object: ...
    def open(self, path: str) -> object: ...
    def history(self, session: object, redo: bool) -> object: ...
    def cancel_job(self, job: object) -> object: ...
    def job_state(self, job: object) -> object: ...
    def _test_control(self, action: str) -> object: ...
    def wait(self, job: object) -> object: ...

class NativeModule(Protocol):
    _Runtime: Callable[[], NativeRuntime]

class SessionToken(Protocol):
    @property
    def runtime(self) -> str: ...
    @property
    def serial(self) -> int: ...
