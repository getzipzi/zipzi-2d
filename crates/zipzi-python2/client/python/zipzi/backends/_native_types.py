from .._generated.resource_backends import NativeResources
from typing import Callable, Literal, Protocol
from .. import ops, sampling
from .._generated.protocols import NativeQueries
from ..events import Cursor
from .._values import Source

class NativeRuntime(NativeQueries, NativeResources, Protocol):
    def bindings(self, session: object, edit: object | None, ids: tuple[str, ...] | None) -> object: ...
    def sample(self, session: object, edit: object | None, poses: sampling.Inputs, checks: sampling.Checks, expected: Source | None) -> object: ...
    def subscribe(self, session: object) -> object: ...
    def events(self, cursor: Cursor, limit: int) -> object: ...
    def parameters(self, session: object, edit: object | None, ids: tuple[str, ...] | None) -> object: ...
    def meshes(self, session: object, edit: object | None, ids: tuple[str, ...]) -> object: ...
    contract: str
    def close(self) -> object: ...
    def create_session(self, document_id: str) -> object: ...
    def info(self, session: object) -> object: ...
    def list_sessions(self) -> object: ...
    def attach(self, runtime: str, serial: int) -> object: ...
    def begin_edit(self, session: object, label: str) -> object: ...
    def apply(self, edit: object, operations: tuple[ops.Operation, ...]) -> object: ...
    def prepare_image(self, width: int, height: int, rgba: bytes) -> object: ...
    def release_handle(self, kind: Literal["image", "plan"], token: object) -> object: ...
    def statistics(self) -> object: ...
    def release_edit(self, edit: object) -> object: ...
    def commit(self, edit: object) -> object: ...
    def save(self, session: object, path: str) -> object: ...
    def open(self, path: str) -> object: ...
    def history(self, session: object, redo: bool) -> object: ...
    def cancel_job(self, job: object) -> object: ...
    def job_state(self, job: object) -> object: ...
    def _test_control(self, action: str) -> object: ...
    def wait(self, job: object) -> object: ...

class NativeModule(Protocol):
    _Runtime: Callable[[], NativeRuntime]

class SessionToken(Protocol):
    @property
    def runtime(self) -> str: ...
    @property
    def serial(self) -> int: ...
