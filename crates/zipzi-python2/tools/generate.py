def identifier(value):
    if not isinstance(value, str) or not re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*', value) or keyword.iskeyword(value):
        raise ValueError('Invalid public identifier')

def rust_path(value):
    if not isinstance(value, str) or not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*(::[A-Za-z_][A-Za-z0-9_]*)+', value):
        raise ValueError('Invalid Rust type/handler path')

class Model:
    def __init__(self, contract, resources=False):
        self.resources = resources
        if contract.get("version") != 1:
            raise ValueError("Unsupported contract version")
        self.bindings = {}
        for binding in contract["bindings"]:
            identifier(binding['name'])
            rust_path(binding['rust'])
            rust_path(binding['path'])
            if binding['module'] not in {'meshes', 'ops', 'backend', 'native', '_values', 'resources', 'plans'}:
                raise ValueError('Unsupported public module')
            if binding["rust"] in self.bindings:
                raise ValueError("Duplicate type binding")
            if binding["form"] not in {"point", "record", "owned_record", "snapshot", "union", "enum", "query", "token", "source", "handle", "version"}:
                raise ValueError("Unsupported public projection")
            self.bindings[binding["rust"]] = binding
        self.types = {}
        for shape in contract["roots"]:
            self.visit(shape)
        for operation in contract["operations"]:
            identifier(operation.get('backend'))
            rust_path(operation.get('handler'))
            if operation.get("category") not in {"query", "planning"} or not operation.get("handler") or not operation.get("capability"):
                raise ValueError("Operation lacks a compiled handler/category/capability")
            if not resources and (operation["name"] != "mesh_snapshot" or operation["backend"] != "mesh"):
                raise ValueError("Operation is outside the reviewed mesh slice")
            self.visit(operation["input"])
            self.visit(operation["output"])
        if not resources and len(contract["operations"]) != 1:
            raise ValueError("Expected exactly the selected query registration")
        self.operation = contract["operations"][0]
        self.records = [self.types[b["rust"]] for b in contract["bindings"] if b["form"] in {"record", "owned_record", "snapshot"}]
        self.union = next(self.types[b["rust"]] for b in contract["bindings"] if b["form"] == "union")
        # Convenience return policies are reviewed API decisions, not fields.
        if not resources and [v["rust_name"] for v in self.union["variants"]] != ["Create", "Rename", "SetPositions"]:
            raise ValueError("New mesh variant requires a reviewed convenience policy")

    def visit(self, shape):
        kind = shape.get("kind")
        if kind in {"string", "u32", "f32", "bool", "u64", "usize", "bytes"}:
            return
        if kind == "string_map":
            if shape.get("value") != {"kind": "string"}:
                raise ValueError("Only the selected string-to-string map is supported")
            return
        if kind in {"sequence", "optional", "array"}:
            if kind == "array" and (shape.get("length") not in {2, 3} or shape.get("item", {}).get("kind") != "u32"):
                raise ValueError("Only selected u32 edge/triangle arrays are supported")
            self.visit(shape["item"])
            return
        if kind not in {"record", "serde_record", "serde_enum", "union", "opaque"} or shape.get("name") not in self.bindings:
            raise ValueError(f"Unselected/unsupported shape: {shape}")
        name = shape["name"]
        if name in self.types:
            if self.types[name] != shape:
                raise ValueError("A Rust type has conflicting field descriptions")
            return
        self.types[name] = shape
        if kind == "serde_enum":
            if self.bindings[name]['form'] != 'enum' or shape.get('tag') is not None or any(v['fields'] for v in shape['variants']):
                raise ValueError('Only selected unit enums are supported')
            return
        fields = shape.get("fields", [])
        if kind == "union":
            if shape["tag"] not in {"op", "kind", "domain"}:
                raise ValueError("Unsupported union discriminator")
            fields = [f for v in shape["variants"] for f in v["fields"]]
            if len({v["wire_name"] for v in shape["variants"]}) != len(shape["variants"]):
                raise ValueError("Duplicate union tag")
        elif len({f["name"] for f in fields}) != len(fields):
            raise ValueError("Duplicate field")
        default_seen = False
        for field in fields:
            identifier(field['name'])
            if field['name'] == 'read' or (kind == 'union' and field['name'] == 'kind'):
                raise ValueError('Field shadows generated API')
            default = field.get("default")
            if default is not None:
                expected = {"null": "optional", "empty_string": "string"}.get(default.get("kind"))
                if expected is None or field['shape'].get('kind') != expected:
                    raise ValueError("Unsupported or incompatible field default")
            if kind in {"record", "serde_record"} and not self.resources:
                if default_seen and default is None:
                    raise ValueError("Required field follows defaulted constructor field")
                default_seen |= default is not None
            self.visit(field["shape"])

    def binding(self, shape):
        return self.bindings[shape["name"]]

    def pytype(self, shape, qualified=False):
        kind = shape["kind"]
        if kind in {"string", "u32", "f32"}:
            return {"string": "str", "u32": "int", "f32": "float"}[kind]
        if kind == "optional":
            return self.pytype(shape["item"], qualified) + " | None"
        if kind == "sequence":
            return f"tuple[{self.pytype(shape['item'], qualified)}, ...]"
        if kind == "array":
            return "tuple[" + ", ".join([self.pytype(shape["item"], qualified)] * shape["length"]) + "]"
        b = self.binding(shape)
        return (b["module"] + "." if qualified and b["module"] == "meshes" else "") + b["name"]

    def read(self, shape, expr):
        kind = shape["kind"]
        if kind in {"string", "u32", "f32"}:
            return f"{{}}({expr})".format({"string": "string", "u32": "integer", "f32": "number"}[kind])
        if kind == "optional":
            return f"None if {expr} is None else {self.read(shape['item'], expr)}"
        if kind == "sequence":
            return f"tuple({self.read(shape['item'], 'item')} for item in sequence({expr}))"
        if kind == "array":
            return f"_array{shape['length']}({expr})"
        b = self.binding(shape)
        if kind == "serde_enum":
            return f"{b['name']}(string({expr}))"
        return f"_point({expr})" if b["form"] == "point" else f"{b['name']}.read({expr})"

    def wire(self, shape, expr):
        kind = shape["kind"]
        if kind in {"string", "u32", "f32"}:
            return expr
        if kind == "optional":
            return f"None if {expr} is None else {self.wire(shape['item'], expr)}"
        if kind in {"sequence", "array"}:
            if shape["item"]["kind"] in {"string", "u32", "f32", "array"}:
                return expr
            return f"[{self.wire(shape['item'], 'item')} for item in {expr}]"
        if kind == "serde_enum":
            return expr + '.value'
        if kind in {"record", "serde_record"}:
            point = self.binding(shape)["form"] == "point"
            fields = [f"{f['name']}={self.wire(f['shape'], expr + ('['+str(i)+']' if point else '.'+f['name']))}" for i, f in enumerate(shape["fields"])]
            return "dict(" + ", ".join(fields) + ")"
        raise ValueError("Unsupported input wire shape")

    def checks(self, shape, expr, indent, serial):
        pad = " " * indent
        kind = shape["kind"]
        if kind == "string":
            return [f"{pad}if not isinstance({expr}, str):", f'{pad}    raise TypeError("Expected text")']
        if kind == "u32":
            return [f"{pad}if type({expr}) is not int or not 0 <= {expr} <= 0xffffffff:", f'{pad}    raise ValueError("Vertex IDs must be u32 integers")']
        if kind == "f32":
            return [f"{pad}if not isinstance({expr}, (float, int)) or isinstance({expr}, bool):", f'{pad}    raise TypeError("Coordinates must be real numbers")',
                f"{pad}if not math.isfinite({expr}) or abs({expr}) > 3.4028234663852886e38:", f'{pad}    raise ValueError("Coordinates must be finite and representable as f32")']
        if kind == "optional":
            return [f"{pad}if {expr} is not None:"] + self.checks(shape["item"], expr, indent + 4, serial)
        if kind in {"sequence", "array"}:
            lines = [f"{pad}if not isinstance({expr}, tuple):", f'{pad}    raise TypeError("Arrays must be owned tuples")']
            if kind == "array":
                lines += [f"{pad}if len({expr}) != {shape['length']}:", f'{pad}    raise TypeError("Invalid fixed array length")']
            serial[0] += 1
            var = f"value{serial[0]}"
            return lines + [f"{pad}for {var} in {expr}:"] + self.checks(shape["item"], var, indent + 4, serial)
        if kind == "serde_enum":
            return [f"{pad}if not isinstance({expr}, {self.binding(shape)['name']}):", f'{pad}    raise TypeError("Invalid constraint kind")']
        if kind in {"record", "serde_record"}:
            point = self.binding(shape)["form"] == "point"
            lines = []
            if point:
                lines += [f"{pad}if not isinstance({expr}, tuple) or len({expr}) != {len(shape['fields'])}:", f'{pad}    raise TypeError("Points must be pairs")']
            for index, f in enumerate(shape["fields"]):
                value = expr + (f"[{index}]" if point else "." + f["name"])
                lines += self.checks(f["shape"], value, indent, serial)
            return lines
        raise ValueError("Unsupported validation shape")

    def native_read(self, shape, expr):
        kind = shape["kind"]
        if kind == 'serde_enum':
            arms = ', '.join('"'+v['name']+'" => '+self.binding(shape)['path']+'::'+v['rust_name'] for v in shape['variants'])
            return '{ match '+expr+'.extract::<String>()?.as_str() { '+arms+', _ => return Err(pyo3::exceptions::PyValueError::new_err("Invalid constraint kind")) } }'
        if kind == 'optional' and shape['item']['kind'] in {'record', 'serde_record'}:
            return '{ let optional = '+expr+'; if optional.is_none() { None } else { Some('+self.native_read(shape['item'], 'optional')+') } }'
        if kind in {"string", "u32", "f32", "optional", "array"}:
            return expr + ".extract()?"
        if kind == "sequence":
            item = shape["item"]
            if item["kind"] == "u32":
                return f"read_ids({expr})?"
            if item["kind"] == "array" and item["length"] == 3 and item["item"]["kind"] == "u32":
                return f"read_triangles({expr})?"
            if item["kind"] == "record" and self.binding(item)["form"] == "point":
                return f"read_points({expr})?"
            if item['kind'] in {'record','serde_record'}:
                return expr+'.try_iter()?.map(|item| Ok('+self.native_read(item,'item?')+')).collect::<PyResult<Vec<_>>>()?'
            raise ValueError("Unsupported native input array")
        return f"read_{self.binding(shape)['name'].lower()}(&{expr})?"

    def native_write(self, shape, expr):
        kind = shape["kind"]
        if kind == 'serde_enum':
            return 'match '+expr+' { '+', '.join(self.binding(shape)['path']+'::'+v['rust_name']+' => "'+v['name']+'"' for v in shape['variants'])+' }'
        if kind == 'optional' and shape['item']['kind'] in {'record', 'serde_record'}:
            return expr+'.map(|value| '+self.native_write(shape['item'], 'value').removesuffix('?')+').transpose()?'
        if kind in {"string", "u32", "f32", "optional", "array"}:
            return expr
        if kind == "sequence":
            item = shape["item"]
            if item["kind"] == "record" and self.binding(item)["form"] == "point":
                return f"points(py, {expr})?"
            if item['kind'] in {'record','serde_record'}:
                return '{ let items = PyList::empty(py); for value in '+expr+' { items.append('+self.native_write(item,'value')+')?; } items }'
            return expr
        b = self.binding(shape)
        if b["form"] == "source":
            return f"source(py, {expr})?"
        return f"write_{b['name'].lower()}(py, {expr})?"


def render_mesh(contract):
    contract = {k: v for k, v in contract.items() if not k.startswith('_')}
    m = Model(contract)
    point = next(s for n, s in m.types.items() if m.bindings[n]["form"] == "point")
    fields = point["fields"]
    if len(fields) != 2 or any(f["shape"]["kind"] != "f32" for f in fields):
        raise ValueError("Point adapter requires exactly two f32 fields")
    mesh = [HEADER.rstrip(), '"""Selected immutable mesh values, derived from Rust declarations."""',
        'from dataclasses import dataclass', 'from collections.abc import Sequence', 'from enum import Enum', 'from .._values import integer, number, record, sequence, string', '',
        'Point = tuple[float, float]', '', 'def _point(value: object) -> Point:', '    r = record(value)',
        '    return (' + ', '.join(m.read(f["shape"], f'r["{f["name"]}"]') for f in fields) + ')', '',
        'def _array3(value: object) -> tuple[int, int, int]:', '    raw = sequence(value)', '    if len(raw) != 3:',
        '        raise ValueError("Invalid triangle")', '    return integer(raw[0]), integer(raw[1]), integer(raw[2])', '']
    mesh += ['def _array2(value: object) -> tuple[int, int]:', '    raw = sequence(value)', '    if len(raw) != 2:', '        raise ValueError("Invalid edge")', '    return integer(raw[0]), integer(raw[1])', '']
    for shape in m.types.values():
        if shape['kind'] == 'serde_enum':
            mesh += ['class '+m.binding(shape)['name']+'(str, Enum):', '    __module__ = "zipzi.meshes"']
            mesh += ['    '+re.sub(r'(?<!^)(?=[A-Z])', '_', v['rust_name']).upper()+' = '+repr(v['name']) for v in shape['variants']]
            mesh += ['']
    for shape in m.records:
        b = m.binding(shape)
        mesh += ['@dataclass(frozen=True'+(', init=False' if b['form']=='owned_record' else '')+')', f'class {b["name"]}:', f'    __module__ = "zipzi.{b["module"]}"']
        value_fields = [f for f in shape["fields"] if b["form"] != "snapshot" or f["name"] != "source"]
        for f in value_fields:
            default = f.get("default")
            suffix = '' if default is None else ' = ' + ('None' if default['kind'] == 'null' else '""')
            mesh.append(f'    {f["name"]}: {m.pytype(f["shape"])}{suffix}')
        if b["form"] == "owned_record":
            def input_type(shape):
                if shape['kind'] in {'sequence','array'}:return 'Sequence['+input_type(shape['item'])+']'
                if shape['kind']=='record' and m.binding(shape)['form']=='point':return 'Sequence[float]'
                return m.pytype(shape)
            mesh += ['', '    def __init__(self, '+', '.join(f['name']+': '+input_type(f['shape'])+(' = None' if f.get('default',{} ) and f['default']['kind']=='null' else '') for f in value_fields)+') -> None:']
            for f in value_fields:
                expr=f['name'];item=f['shape'].get('item',{})
                if f['shape']['kind'] in {'sequence','array'}:
                    expr='tuple(tuple(item) for item in '+expr+')' if item.get('kind') == 'array' or (item.get('kind')=='record' and m.binding(item)['form']=='point') else 'tuple('+expr+')'
                mesh += ['        object.__setattr__(self, '+repr(f['name'])+', '+expr+')']
            mesh += ['        self.__post_init__()', '', '    def __post_init__(self) -> None:']
            # Constructor checks only ownership/shape; finite/range validation
            # belongs to the common write conversion, not geometry algorithms.
            for f in shape["fields"]:
                if f['shape']['kind'] not in {'sequence', 'array'}:
                    continue
                expr = 'self.' + f['name']
                mesh += [f'        if not isinstance({expr}, tuple):', '            raise TypeError("Geometry arrays must be tuples")']
                item = f['shape']['item']
                size = item['length'] if item['kind'] == 'array' else len(item.get('fields', [])) if item['kind'] == 'record' else 0
                if size:
                    mesh += [f'        if any(not isinstance(item, tuple) or len(item) != {size} for item in {expr}):', '            raise TypeError("Invalid geometry array shape")']
        mesh += ['', '    @classmethod', f'    def read(cls, value: object) -> "{b["name"]}":', '        if isinstance(value,cls): return value', '        r = record(value)',
            '        return cls(' + ', '.join(m.read(f['shape'], ('r.get("' + f['name'] + '", ' + ('None' if f['default']['kind'] == 'null' else '""') + ')') if f.get('default') else f'r["{f["name"]}"]') for f in value_fields) + ')', '']
    ops = [HEADER.rstrip(), 'from collections.abc import Sequence', 'from dataclasses import dataclass, field', 'from typing import Literal', 'import math',
        'from .meshes import Geometry, MeshSpec, Point', '']
    for v in m.union['variants']:
        owns = any(f['shape']['kind']=='sequence' for f in v['fields'])
        ops += ['@dataclass(frozen=True'+(', init=False' if owns else '')+')', f'class {v["rust_name"]}:', '    __module__ = "zipzi.meshes"']
        for f in v['fields']:
            default = ' = field(default=None, kw_only=True)' if f['shape']['kind']=='optional' else ''
            ops += [f'    {f["name"]}: {m.pytype(f["shape"])}'+default]
        ops += [f'    kind: Literal["{v["wire_name"]}"] = field(default="{v["wire_name"]}", init=False)']
        if owns:
            args=[f['name']+': '+('Sequence['+m.pytype(f['shape']['item'])+']' if f['shape']['kind']=='sequence' else m.pytype(f['shape'])) for f in v['fields']]
            ops += ['', '    def __init__(self, '+', '.join(args)+') -> None:']
            for f in v['fields']:
                expr=f['name']
                if f['shape']['kind']=='sequence':
                    item=f['shape']['item'];expr=('tuple(tuple(item) for item in '+expr+')' if item['kind']=='record' else 'tuple('+expr+')')
                ops += ['        object.__setattr__(self, '+repr(f['name'])+', '+expr+')']
        ops += ['']
    union = ' | '.join(v['rust_name'] for v in m.union['variants'])
    ops += [f'MeshOperation = {union}', '', 'def validate(op: MeshOperation) -> None:', '    match op:']
    for v in m.union['variants']:
        ops += [f'        case {v["rust_name"]}():']
        for f in v['fields']:
            ops += m.checks(f['shape'], 'op.' + f['name'], 12, [0])
    ops += ['', 'def wire(op: MeshOperation) -> dict[str, object]:', '    match op:']
    for v in m.union['variants']:
        expr = ', '.join(f'{f["name"]}={m.wire(f["shape"], "op."+f["name"])}' for f in v['fields'])
        ops += [f'        case {v["rust_name"]}():', f'            return dict(op="{v["wire_name"]}", {expr})']
    ops += ['    raise TypeError("Unknown mesh operation")', '']
    # Do not publish unused imports merely to make a template convenient.
    ops.remove('from .meshes import Geometry, MeshSpec, Point')
    ops.insert(5, 'from .meshes import MeshSpec, Point'+''.join(', '+m.binding(s)['name'] for s in m.types.values() if s['kind']=='serde_enum'))
    query = m.operation['input']
    fields = query['fields']
    def parameter_type(shape, native=False):
        kind = shape['kind']
        if kind == 'opaque' and m.binding(shape)['form'] == 'token':
            return '&' + m.binding(shape)['name'] if native else 'object'
        if kind == 'optional':
            inner = parameter_type(shape['item'], native)
            return f'Option<{inner}>' if native else inner + ' | None'
        if kind in {'string', 'u32', 'f32'}:
            return {'string': '&str', 'u32': 'u32', 'f32': 'f32'}[kind] if native else m.pytype(shape)
        raise ValueError('Query requires a reviewed ownership adapter')
    def token_input(f):
        shape, name = f['shape'], f['name']
        if shape['kind'] == 'opaque':
            return name + '.id'
        if shape['kind'] == 'optional' and shape['item']['kind'] == 'opaque':
            return name + '.map(|value| value.id)'
        return name+'.to_owned()' if shape['kind']=='string' else name
    params = ', '.join(f"{f['name']}: {parameter_type(f['shape'])}" for f in fields)
    native_params = ', '.join(f"{f['name']}: {parameter_type(f['shape'], True)}" for f in fields)
    names = ', '.join(f['name'] for f in fields)
    method = m.operation['backend']
    protocols = HEADER + 'from typing import Protocol\n\nclass MeshBackend(Protocol):\n'
    protocols += f'    def {method}(self, {params}, owner: object) -> object: ...\n\nclass NativeQueries(Protocol):\n'
    protocols += f'    def {method}(self, {params}) -> object: ...\n'
    def record_names(shape):
        kind = shape['kind']
        children = [f['shape'] for f in shape.get('fields', [])]
        if kind in {'sequence', 'optional', 'array'}:
            children.append(shape['item'])
        if kind == 'union':
            children += [f['shape'] for v in shape['variants'] for f in v['fields']]
        result = {shape['name']} if kind in {'record','serde_record'} else set()
        for child in children:
            result |= record_names(child)
        return result
    inputs = record_names(m.union)
    outputs = record_names(m.operation['output'])
    rust = [RUST_HEADER.rstrip(), 'use crate::*;', '',
        f"pub(crate) fn read_points(value: Bound<'_, PyAny>) -> PyResult<Vec<{m.binding(point)['path']}>> {{",
        '    let pairs = value.extract::<Vec<(f32, f32)>>()?;',
        '    zipzi_runtime::metrics::materialized_input(pairs.len() * std::mem::size_of::<(f32, f32)>());',
        '    Ok(pairs.into_iter().map(|point| ' + m.binding(point)['path'] + ' { ' + ', '.join(f['name'] + ': point.' + str(i) for i, f in enumerate(point['fields'])) + ' }).collect())',
        '}', '',
        f"pub(crate) fn points(py: Python<'_>, values: Vec<{m.binding(point)['path']}>) -> PyResult<Bound<'_, PyList>> {{",
        '    let result = PyList::empty(py);', '    for value in values {', '        let d = PyDict::new(py);',
        *[f'        d.set_item("{f["name"]}", value.{f["name"]})?;' for f in point['fields']],
        '        result.append(d)?;', '    }', '    Ok(result)', '}', '']
    for shape in m.records:
        b = m.binding(shape)
        name = b['name'].lower()
        if shape['name'] in inputs:
            rust += [f'pub(crate) fn read_{name}(value: &Bound<\'_, PyAny>) -> PyResult<{b["path"]}> {{', f'    Ok({b["path"]} {{']
            rust += [f'        {f["name"]}: {m.native_read(f["shape"], "value.getattr(\""+f["name"]+"\")?")},' for f in shape['fields']]
            rust += ['    })', '}', '']
        if shape['name'] not in outputs:
            continue
        rust += [f'pub(crate) fn write_{name}(py: Python<\'_>, value: {b["path"]}) -> PyResult<Bound<\'_, PyDict>> {{', '    let d = PyDict::new(py);']
        rust += [f'    d.set_item("{f["name"]}", {m.native_write(f["shape"], "value."+f["name"])})?;' for f in shape['fields']]
        rust += ['    Ok(d)', '}', '']
    rust += ['pub(crate) fn read_mesh_operation(kind: &str, op: &Bound<\'_, PyAny>) -> PyResult<MeshOperation> {', '    match kind {']
    for v in m.union['variants']:
        rust += [f'        "{v["wire_name"]}" => Ok(MeshOperation::{v["rust_name"]} {{']
        rust += [f'            {f["name"]}: {m.native_read(f["shape"], "op.getattr(\""+f["name"]+"\")?")},' for f in v['fields']]
        rust += ['        }),']
    rust += ['        _ => Err(pyo3::exceptions::PyTypeError::new_err("Unknown mesh operation")),', '    }', '}', '']
    query_path = m.binding(query)['path']
    input_fields = ', '.join(f['name'] if token_input(f) == f['name'] else f'{f["name"]}: {token_input(f)}' for f in fields)
    signature = ', '.join(f['name'] + ('=None' if f['default'] is not None else '') for f in fields)
    output_writer = 'write_' + m.binding(m.operation['output'])['name'].lower()
    queries = RUST_HEADER + '\n'.join([
        'use crate::*;', f'use super::mesh::{output_writer};', '#[pymethods]', 'impl NativeRuntime {',
        f'    #[pyo3(signature = ({signature}))]',
        f"    fn {method}(&self, py: Python<'_>, {native_params}) -> PyResult<Py<PyDict>> {{",
        '        let _input=input_lease!(self,py,id.len().saturating_mul(4),"meshes.get",None);', '        let client = self.client;', f'        let input = {query_path} {{ {input_fields} }};',
        f'        let value = py.detach(|| self.host.call(move |rt| {{let lease=rt.reserve_transfer(rt.mesh_read_bytes(client,input.session,input.edit,std::slice::from_ref(&input.id))?)?;Ok(({m.operation["handler"]}.call(rt, client, input)?,lease))}}));',
        f'        reply(py, value, "meshes.get", |(value,_lease)| Ok({output_writer}(py, value)?.into_any()))', '    }', '}', '',
    ])
    output = {
        'schema/authoring.json': json.dumps(dict(contract, _generated_by=OWNER, _contract_sha256=hashlib.sha256(json.dumps(contract, sort_keys=True).encode()).hexdigest()), indent=2, sort_keys=True) + '\n',
        'client/python/zipzi/_generated/__init__.py': HEADER + '"""Compiled authoring contract outputs. Do not edit by hand."""\n',
        'client/python/zipzi/_generated/meshes.py': '\n'.join(mesh),
        'client/python/zipzi/_generated/mesh_ops.py': '\n'.join(ops),
        'client/python/zipzi/_generated/protocols.py': protocols,
        'src/generated/mod.rs': RUST_HEADER + 'pub mod mesh;\npub mod queries;\npub mod resources;\npub mod resource_queries;\n',
        'src/generated/mesh.rs': '\n'.join(rust),
        'src/generated/queries.rs': queries,
    }
    return output


def render(contract):
    contract={k:v for k,v in contract.items() if not k.startswith('_')}
    render_resources = _resource_codegen.render_resources
    mesh_contract = {k: v for k, v in contract.items() if k not in {'resources', 'scene', 'modeling', 'binary', 'dtos', 'runtime'}}
    output = render_mesh(mesh_contract)
    # The root intermediate is the complete executable contract.
    output['schema/authoring.json'] = json.dumps(dict(contract, _generated_by=OWNER), indent=2, sort_keys=True) + '\n'
    output.update(render_resources(contract['resources'], Model, HEADER, RUST_HEADER))
    output.update(_scene_codegen.render_scene(contract['scene'], HEADER, RUST_HEADER, identifier, rust_path))
    output.update(_modeling_codegen.render_modeling(contract['modeling'], HEADER, RUST_HEADER))
    output.update(_binary_codegen.render_binary(contract['binary'], HEADER))
    output.update(_dto_codegen.render_dtos(contract['dtos'], HEADER))
    output.update(_api_codegen.render_api(contract, HEADER, RUST_HEADER))
    output['src/generated/mod.rs'] += 'pub mod scene;\npub mod modeling;\npub mod discovery;\n'
    output.update(_catalog_codegen.render_catalog(contract, output, HEADER, PACKAGE, _dto_codegen.NAMES, _modeling_codegen.public_name))
    # rustfmt only sees generated scratch files, never handwritten sources.
    import tempfile
    with tempfile.TemporaryDirectory(prefix='zipzi-codegen-') as folder:
        for path, content in list(output.items()):
            if path.endswith('.rs'):
                temporary = Path(folder) / Path(path).name
                temporary.write_text(content, encoding='utf-8')
                subprocess.run(['rustfmt', '--edition', '2021', '--config', 'style_edition=2024,skip_children=true', str(temporary)], check=True, capture_output=True)
                output[path] = temporary.read_text(encoding='utf-8')
    return output


def export():
    environment = dict(os.environ)
    environment.setdefault('PYO3_PYTHON', sys.executable)
    result = subprocess.run(['cargo', 'run', '--locked', '--quiet', '-p', 'zipzi-python2', '--example', 'authoring_schema'], cwd=ROOT, env=environment, capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError(result.stderr)
    return json.loads(result.stdout)


def write_outputs(output, check=False, package=PACKAGE):
    # Validate the complete mutation set before writing any file.
    if set(output) != TARGETS:
        raise ValueError('Attempt to overwrite an unowned/handwritten file')
    for folder in ('client/python/zipzi/_generated', 'src/generated'):
        for file in (package / folder).rglob('*'):
            if file.is_file() and '__pycache__' not in file.parts and file.relative_to(package).as_posix() not in output:
                raise ValueError(f'Unmanaged file in generated directory: {file}')
    differences = []
    for path, content in output.items():
        file = package / path
        traverses_link = any(package.joinpath(*Path(path).parts[:index]).is_symlink()
            for index in range(1, len(Path(path).parts) + 1))
        if not file.resolve().is_relative_to(package.resolve()) or traverses_link:
            raise ValueError('Generated path traverses a symlink/outside package')
        existing = file.read_text(encoding='utf-8') if file.is_file() else None
        if existing is not None:
            owned = json.loads(existing).get('_generated_by') == OWNER if path.endswith('.json') else existing.startswith((HEADER, RUST_HEADER))
            if not owned:
                raise ValueError(f'Refusing to overwrite handwritten file: {path}')
        if existing != content:
            differences.append(path)
    if not check:
        for path in differences:
            file = package / path
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(output[path], encoding='utf-8')
    return differences


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Compare only; do not write sources')
    parser.add_argument('--schema', type=Path, help='Replay an exported intermediate schema for diagnostics')
    args = parser.parse_args()
    contract = json.loads(args.schema.read_text(encoding='utf-8')) if args.schema else export()
    output = render(contract)
    changes = write_outputs(output, args.check)
    if args.check and changes:
        raise SystemExit('Generated drift: ' + ', '.join(changes))
    print('zipzi-python2 authoring contract: ' + ('verified' if args.check else 'generated') + f' {len(output)} files')

if __name__ == '__main__':
    main()
